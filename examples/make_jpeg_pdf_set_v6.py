"""Create valid and decoy JPEG/PDF images for carving evaluation."""

from __future__ import annotations

import csv
import hashlib
import random
from pathlib import Path

try:
    from PIL import Image
    from pypdf import PdfReader, PdfWriter
except ImportError as error:
    raise SystemExit("Install optional validation dependencies: .venv/Scripts/python.exe -m pip install -e '.[validation]'") from error


ROOT = Path(__file__).resolve().parent / "experiment_set_v6"
IMAGE_DIR = ROOT / "images"
SOURCE_DIR = ROOT / "sources"
SAMPLE_COUNT = 10


def _write_jpeg(path: Path, sample_number: int) -> None:
    width, height = 24 + sample_number * 5, 19 + sample_number * 3
    rng = random.Random(307000 + sample_number)
    image = Image.new("RGB", (width, height))
    for index in range(width * height):
        x, y = index % width, index // width
        image.putpixel((x, y), tuple(rng.randrange(256) for _ in range(3)))
    image.save(path, format="JPEG", quality=40 + sample_number * 5, optimize=sample_number % 2 == 0)


def _write_pdf(path: Path, sample_number: int) -> None:
    writer = PdfWriter()
    writer.add_blank_page(width=200 + sample_number * 7, height=300 + sample_number * 9)
    writer.add_metadata({"/Title": f"PDRS synthetic PDF sample {sample_number:02d}"})
    with path.open("wb") as handle:
        writer.write(handle)


def main() -> None:
    if ROOT.exists():
        raise SystemExit(f"Refusing to overwrite existing dataset: {ROOT}\nMove it aside or use a fresh project copy.")
    IMAGE_DIR.mkdir(parents=True)
    SOURCE_DIR.mkdir(parents=True)
    rows: list[dict[str, object]] = []

    for sample_number in range(1, SAMPLE_COUNT + 1):
        sample_id = f"sample_{sample_number:02d}"
        sources: dict[str, Path] = {}
        for fmt in ("jpeg", "pdf"):
            source = SOURCE_DIR / f"{sample_id}.{fmt}"
            if fmt == "jpeg":
                _write_jpeg(source, sample_number)
            else:
                _write_pdf(source, sample_number)
            sources[fmt] = source

        # Ensure generated controls are parseable before embedding them.
        with Image.open(sources["jpeg"]) as image:
            image.load()
        reader = PdfReader(sources["pdf"], strict=True)
        try:
            if len(reader.pages) != 1:
                raise ValueError(f"Unexpected PDF page count in {sources['pdf'].name}")
        finally:
            reader.close()

        for fmt in ("jpeg", "pdf"):
            source_bytes = sources[fmt].read_bytes()
            for kind in ("valid", "decoy"):
                scenario = f"{fmt}_{kind}"
                filler = bytes([0x31 + sample_number]) * 47
                prefix = f"PDRS-{scenario}-{sample_id}\x00".encode("ascii") + filler
                offset = len(prefix)
                if kind == "valid":
                    embedded = source_bytes
                    target_present = True
                    note = f"valid {fmt.upper()} generated by independent library"
                    source_filename = sources[fmt].name
                    source_hash = hashlib.sha256(source_bytes).hexdigest()
                elif fmt == "jpeg":
                    embedded = b"\xff\xd8\xff\xe0PDRS fake JPEG signature only\xff\xd9"
                    target_present = False
                    note = "JPEG start/end marker decoy; not a decodable image"
                    source_filename = ""
                    source_hash = ""
                else:
                    embedded = b"%PDF-1.4\nPDRS fake PDF signature only\n%%EOF\n"
                    target_present = False
                    note = "PDF header and EOF marker decoy; no valid xref or objects"
                    source_filename = ""
                    source_hash = ""

                image_name = f"{scenario}_{sample_id}.img"
                (IMAGE_DIR / image_name).write_bytes(prefix + embedded + b"\x00PDRS-END")
                rows.append({
                    "scenario": scenario,
                    "sample_id": sample_id,
                    "format": fmt,
                    "target_present": target_present,
                    "image_filename": image_name,
                    "source_filename": source_filename,
                    "expected_offset": offset,
                    "source_size_bytes": len(source_bytes) if target_present else 0,
                    "source_sha256": source_hash,
                    "embedded_size_bytes": len(embedded),
                    "scenario_note": note,
                })

    with (ROOT / "ground_truth.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print(f"Samples per scenario: {SAMPLE_COUNT}")
    print(f"Scenario images:      {len(rows)} (JPEG/PDF valid and decoy)")
    print(f"Images:      {IMAGE_DIR}")
    print(f"Sources:     {SOURCE_DIR}")
    print(f"Ground truth:{ROOT / 'ground_truth.csv'}")


if __name__ == "__main__":
    main()
